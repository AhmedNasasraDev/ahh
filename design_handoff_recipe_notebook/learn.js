function fmt(n) {
  return '₪' + (n >= 100 ? Math.round(n) : Math.round(n * 10) / 10);
}

function cards(c, r) {
  return PRINCIPLES.filter(p => {
    try { return p.when(c, r); } catch (e) { return false; }
  }).map(p => ({ id: p.id, title: p.title, body: p.body, calc: p.calc(c, r), what: p.what(c, r) }));
}

// תרגול: מה יקרה אם משנים רכיב אחד. התשובה מגיעה מהמנוע, לא מניחוש.
function drills(c, r, engine, recipes) {
  const out = [];
  if (c.flour > 0) {
    const liq = (r.ingredients || []).find(i => i.liquid);
    if (liq) {
      const delta = Math.round(c.flour * 0.05);
      const patched = Object.assign({}, r, {
        ingredients: r.ingredients.map(i => i === liq
          ? Object.assign({}, i, { qty: Math.max(0, Number(i.qty) - delta), unit: i.unit }) : i),
      });
      const c2 = engine.compute(patched, recipes, c.factor || 1);
      out.push({
        q: 'מה יקרה אם תוריד ' + delta + ' גרם מ' + liq.name + '?',
        a: 'ההידרציה תרד מ־' + c.hydration.toFixed(1) + '% ל־' + c2.hydration.toFixed(1) +
          '%, והתשואה תרד ל־' + engine.fmtG(c2.actualYield) + '. הבצק יהיה הדוק יותר וייקח יותר זמן להתפתח.',
      });
    }
  }
  if (c.bakeLoss > 0 && c.scaleWeight) {
    out.push({
      q: 'למה שוקלים ' + Math.round(c.scaleWeight) + ' גרם ליחידה ולא את המשקל הסופי?',
      a: 'כי באפייה מתאדים ' + c.bakeLoss.toFixed(1) + '% מהמשקל. שקילה של המשקל הסופי תיתן יחידה קטנה מהמתוכנן.',
    });
  }
  if (c.cost > 0 && c.price) {
    const p2 = c.costPerUnit / 0.30;
    out.push({
      q: 'מה יקרה למחיר אם תוריד את יעד הפוד קוסט ל־30%?',
      a: 'המחיר ליחידה ירד מ־' + fmt(c.price) + ' ל־' + fmt(p2) + ', כלומר פחות רווח גולמי על אותה עלות.',
    });
  }
  return out;
}

window.PN_LEARN = { cards, drills };
